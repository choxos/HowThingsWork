import {createSparkGapModel} from './spark-gap-model.js';
import {createSolenoidModel} from './solenoid-model.js';
import {createSparkPlugModel} from './spark-plug-model.js';
import {createCarIgnitionModel} from './car-ignition-model.js';
import {createPowerPylonModel} from './power-pylon-model.js';
import {createPowerLineInsulatorModel} from './power-line-insulator-model.js';
import {createHomeSupplyTransformerModel} from './home-supply-transformer-model.js';
import {createElectricityTransmissionModel} from './electricity-transmission-model.js';
import {createTransformerModel} from './transformer-model.js';
import {createElectricGeneratorModel} from './electric-generator-model.js';
import {createPrinterModel} from './printer-model.js';
import {createCADDesignModel} from './cad-design-model.js';
import {createLaserScanningModel} from './laser-scanning-model.js';
import {createStepperMotorModel} from './stepper-motor-model.js';
import {createUniversalMotorModel} from "./universal-motor-model.js";
import {createDCMotorModel} from './dc-motor-model.js';
import {createElectromagnetModel} from './electromagnet-model.js';
import {createBellModel} from './bell-model.js';
import {createHornModel} from './horn-model.js';
import {createRatchetModel} from './ratchet-model.js';
import {createWindowShadeModel} from './window-shade-model.js';
import {createTweezersModel} from './tweezers-model.js';
import {createClipperModel} from './clipper-model.js';
import {createCylinderModel} from './cylinder-model.js';
import {createLeverModel} from './lever-model.js';
import {createZipperModel} from './zipper-model.js';

export function createDailyLifeMachine(name) {
  if(name==='Spark gap')return createSparkGapModel();
  if(name==='Solenoid')return createSolenoidModel();
  if(name==='Spark plug')return createSparkPlugModel();
  if(name==='Ignition-coil primary and secondary windings')return createCarIgnitionModel({ignitionWindingsLesson:true});
  if(name==='Induction coil')return createCarIgnitionModel({inductionCoilLesson:true});
  if(name==='Distributor')return createCarIgnitionModel({distributorLesson:true});
  if(name==='Contact-breaker ignition')return createCarIgnitionModel({contactBreakerLesson:true});
  if(name==='Car ignition system')return createCarIgnitionModel();
  if(name==='Power pylon')return createPowerPylonModel();
  if(name==='Power-line insulator')return createPowerLineInsulatorModel();
  if(name==='Home-supply transformer')return createHomeSupplyTransformerModel();
  if(name==='Distribution transformer')return createElectricityTransmissionModel({distributionLesson:true});
  if(name==='Transmission transformer')return createElectricityTransmissionModel({sendingLesson:true});
  if(name==='Electricity transmission')return createElectricityTransmissionModel();
  if(name==='Transformer turns ratio')return createTransformerModel({turnsRatioLesson:true});
  if(name==='Transformer')return createTransformerModel();
  if(name==='Generator slip rings')return createElectricGeneratorModel({slipRingLesson:true});
  if(name==='DC generator')return createElectricGeneratorModel({commutationLesson:true});
  if(name==='AC generator')return createElectricGeneratorModel({alternating:true});
  if(name==='Electric generator')return createElectricGeneratorModel();
  if(name==='Laser scanning of 3D objects')return createLaserScanningModel();
  if(name==='Computer-aided design')return createCADDesignModel();
  if(name==='Three-axis positioning')return createPrinterModel({positioning:true});
  if(name==='3D printer')return createPrinterModel();
  if(name==='Stepper motor')return createStepperMotorModel();
  if(name==='Electric motor')return createDCMotorModel();
  if(name==="Universal motor")return createUniversalMotorModel();
  if(name==='Direct-current motor')return createDCMotorModel();
  if(name==='Electromagnet')return createElectromagnetModel();
  if(name==='Cylinder lock')return createCylinderModel();
  if(name==='Keys')return createCylinderModel({editableKey:true});
  if(name==='Lever lock')return createLeverModel();
  if(name==='Zipper')return createZipperModel();
  if(name==='Nail clippers')return createClipperModel();
  if(name==='Tweezers')return createTweezersModel();
  if(name==='Window shade')return createWindowShadeModel();
  if(name==='Ratchet')return createRatchetModel();
  if(name==='Electric bell')return createBellModel();
  if(name==='Electric horn')return createHornModel();
  return null;
}
