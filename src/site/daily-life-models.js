export function createDailyLifeMachine(name) {
  if(name==='Raft')return createRaftModel();
  if(name==='Electric generator')return createGeneratorModel();
  if(name==='Transformer')return createGridTransformerModel();
  if(name==='Electricity transmission')return createLineModel();
  if(name==='Liquid crystal display')return createLCDModel();
  if(name==='Polarized light')return createPolarizedLightModel();
  if(name==='Microscopes')return createMicroscopesModel();
  if(name==='Binoculars')return createBinocularsModel();
  if(name==='Telescopes')return createTelescopesModel();
  if(name==='Lenses')return createLensesModel();
  if(name==='Mirrors')return createMirrorsModel();
  if(name==='Airbag warning indicator')return createAirbagWarningIndicatorModel();
  if(name==='Crash sensor')return createCrashSensorModel();
  if(name==='Autopilot')return createAutopilotModel();
  if(name==='Inertial accelerometer armature, spring, and coils')return createInertialAccelerometerModel();
  if(name==='Inertial guidance')return createInertialGuidanceModel();
  if(name==='Seismograph recording pen and moving paper')return createSeismographRecordingModel();
  if(name==='Vertical-seismograph suspension spring')return createVerticalSeismographSpringModel();
  if(name==='Earthquake location by arrival times')return createEarthquakeLocationModel();
  if(name==='Seismic waves')return createSeismicWavesModel();
  if(name==='Vertical seismograph pendulum')return createVerticalSeismographPendulumModel();
  if(name==='Horizontal seismograph pendulum')return createHorizontalSeismographPendulumModel();
  if(name==='Seismograph')return createSeismographModel();
  if(name==='Feedback mechanism')return createFeedbackMechanismModel();
  if(name==='Sensors and detectors')return createSensorsAndDetectorsModel();
  if(name==='Electronic ignition')return createElectronicIgnitionModel();
  if(name==='Spark gap')return createSparkGapModel();
  if(name==='Solenoid')return createSolenoidModel();
  if(name==='Spark-plug electrodes and ceramic insulator')return createSparkPlugModel({electrodesLesson:true});
  if(name==='Spark plug')return createSparkPlugModel();
  if(name==='Ignition-coil primary and secondary windings')return createCarIgnitionModel({ignitionWindingsLesson:true});
  if(name==='Induction coil')return createCarIgnitionModel({inductionCoilLesson:true});
  if(name==='Distributor')return createCarIgnitionModel({distributorLesson:true});
  if(name==='Contact-breaker ignition')return createCarIgnitionModel({contactBreakerLesson:true});
  if(name==='Car ignition system')return createCarIgnitionModel();
  if(name==='Laser scanning of 3D objects')return createLaserScanningModel();
  if(name==='Computer-aided design')return createCADDesignModel();
  if(name==='Three-axis positioning')return createThreeAxisModel();
  if(name==='3D printer')return createPrinterModel();
  if(name==='Stepper motor')return createStepperMotorModel();
  if(name==='Electric motor')return createDCMotorModel();
  if(name==="Universal motor")return createUniversalMotorModel();
  if(name==='Direct-current motor')return createDCMotorModel();
  if(name==='Electromagnet')return createElectromagnetModel();
  if(name==='Cylinder lock')return createCylinderModel();
  if(name==='Keys')return createCylinderModel({editableKey:true});
  if(name==='Lever lock')return createLeverModel();
  if(name==='Zipper')return createZipperModel();
  if(name==='Nail clippers')return createClipperModel();
  if(name==='Tweezers')return createTweezersModel();
  if(name==='Window shade')return createWindowShadeModel();
  if(name==='Ratchet')return createRatchetModel();
  if(name==='Electric bell')return createBellModel();
  if(name==='Electric horn')return createHornModel();
  return null;
}
