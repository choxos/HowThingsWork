import {createCanOpenerModel} from './can-opener-model.js';
import {createBottleOpenerModel} from './bottle-opener-model.js';
import {createNutcrackerModel} from './nutcracker-model.js';
import {createSardineCanKeyModel} from './sardine-can-key-model.js';
import {createSaladSpinnerModel} from './salad-spinner-model.js';
import {createScrewCorkscrewModel} from './screw-corkscrew-model.js';
import {createWingedCorkscrewModel} from './winged-corkscrew-model.js';
import {createEggWhiskModel} from './egg-whisk-model.js';
import {createElectricMixerModel} from './electric-mixer-model.js';
import {createMeatGrinderModel} from './meat-grinder-model.js';
import {createDrinkingStrawModel} from './drinking-straw-model.js';
import {createDishwasherModel} from './dishwasher-model.js';
import {createMicrowaveModel} from './microwave-model.js';
import {createVacuumFlaskModel} from './vacuum-flask-model.js';
import {createToasterModel} from './toaster-model.js';
import {createRefrigeratorModel} from './refrigerator-model.js';
const names=['Can opener','Bottle opener','Nutcracker','Sardine-can key','Salad spinner','Rack-and-pinion corkscrew','Egg whisk','Electric mixer','Screw corkscrew','Meat grinder','Drinking straw','Dishwasher','Microwave oven','Vacuum flask','Toaster','Refrigerator'];
export function createKitchenModel(name){
 if(!names.includes(name))return null;
 if(name==='Can opener')return createCanOpenerModel();
 if(name==='Bottle opener')return createBottleOpenerModel();
 if(name==='Nutcracker')return createNutcrackerModel();
 if(name==='Sardine-can key')return createSardineCanKeyModel();
 if(name==='Salad spinner')return createSaladSpinnerModel();
 if(name==='Screw corkscrew')return createScrewCorkscrewModel();
 if(name==='Rack-and-pinion corkscrew')return createWingedCorkscrewModel();
 if(name==='Egg whisk')return createEggWhiskModel();
 if(name==='Electric mixer')return createElectricMixerModel();
 if(name==='Meat grinder')return createMeatGrinderModel();
 if(name==='Drinking straw')return createDrinkingStrawModel();
 if(name==='Dishwasher')return createDishwasherModel();
 if(name==='Microwave oven')return createMicrowaveModel();
 if(name==='Vacuum flask')return createVacuumFlaskModel();
 if(name==='Toaster')return createToasterModel();
 if(name==='Refrigerator')return createRefrigeratorModel();
 return null;
}
